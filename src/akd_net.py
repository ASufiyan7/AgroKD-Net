# CELL 9 — Build a lightweight segmentation student

import torch
import torch.nn as nn
import torch.nn.functional as F
from torchvision.models import mobilenet_v3_large, MobileNet_V3_Large_Weights

class AgroKDStudent(nn.Module):
    def __init__(self, num_classes=2, pretrained=True):
        super().__init__()

        weights = MobileNet_V3_Large_Weights.DEFAULT if pretrained else None
        backbone = mobilenet_v3_large(weights=weights)

        self.encoder = backbone.features
        encoder_channels = 960

        self.decoder = nn.Sequential(
            nn.Conv2d(encoder_channels, 256, kernel_size=1, bias=False),
            nn.BatchNorm2d(256),
            nn.ReLU(inplace=True),
            nn.Conv2d(256, 128, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(128),
            nn.ReLU(inplace=True),
            nn.Conv2d(128, num_classes, kernel_size=1)
        )

    def forward(self, x):
        output_size = x.shape[-2:]
        features = self.encoder(x)
        logits = self.decoder(features)
        return F.interpolate(
            logits,
            size=output_size,
            mode="bilinear",
            align_corners=False
        )

student = AgroKDStudent(num_classes=NUM_CLASSES).to(DEVICE)

