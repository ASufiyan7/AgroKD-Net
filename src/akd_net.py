def calculate_metrics(model, loader):
    model.eval()
    confusion = torch.zeros(
        NUM_CLASSES, NUM_CLASSES, dtype=torch.int64
    )

    total_loss = 0.0
    batches = 0

    with torch.no_grad():
        for images, masks in loader:
            images = images.to(DEVICE)
            masks = masks.to(DEVICE)

            logits = model(images)["out"]
            loss = criterion(logits, masks)

            preds = logits.argmax(dim=1)
            encoded = masks.reshape(-1) * NUM_CLASSES + preds.reshape(-1)

            confusion += torch.bincount(
                encoded.cpu(),
                minlength=NUM_CLASSES * NUM_CLASSES
            ).reshape(NUM_CLASSES, NUM_CLASSES)

            total_loss += loss.item()
            batches += 1

    confusion_f = confusion.float()
    intersection = confusion_f.diag()
    union = confusion_f.sum(0) + confusion_f.sum(1) - intersection

    iou = intersection / union.clamp_min(1)
    miou = iou.mean().item()
    accuracy = intersection.sum().item() / confusion_f.sum().clamp_min(1).item()

    return {
        "loss": total_loss / max(batches, 1),
        "accuracy": accuracy,
        "iou_background": iou[0].item(),
        "iou_plant": iou[1].item(),
        "miou": miou,
        "confusion": confusion
    }

best_miou = -1.0
history_teacher = []

for epoch in range(1, EPOCHS_TEACHER + 1):
    teacher.train()
    running_loss = 0.0
    start_time = time.time()

    for images, masks in train_loader:
        images = images.to(DEVICE)
        masks = masks.to(DEVICE)

        optimizer.zero_grad(set_to_none=True)

        logits = teacher(images)["out"]
        loss = criterion(logits, masks)

        loss.backward()
        optimizer.step()

        running_loss += loss.item()

