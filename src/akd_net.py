import time
import torch
import pandas as pd
import numpy as np

baseline_eval.eval()
kd_eval.eval()

# Same input shape and device for both models
sample = torch.randn(1, 3, 192, 256, device=DEVICE)

def synchronize():
    if DEVICE.type == "cuda":
        torch.cuda.synchronize()

@torch.inference_mode()
def predict(model):
    output = model(sample)
    return output["out"] if isinstance(output, dict) else output

# Warm up both models
for _ in range(30):
    predict(baseline_eval)
    predict(kd_eval)

synchronize()

# Alternate measurements to reduce order-related bias
latencies = {
    "Baseline student": [],
    "KD student": []
}

models_to_test = [
    ("Baseline student", baseline_eval),
    ("KD student", kd_eval)
]

for repeat in range(7):
    # Alternate order across repetitions
    current_order = (
        models_to_test if repeat % 2 == 0
        else models_to_test[::-1]
    )

    for name, model in current_order:
        synchronize()
        start = time.perf_counter()

        for _ in range(100):
            predict(model)

        synchronize()
        elapsed = time.perf_counter() - start

        latencies[name].append(elapsed * 1000 / 100)

rows = []

for name, values in latencies.items():
    median_ms = float(np.median(values))
    rows.append({
        "Model": name,
        "Median latency (ms/image)": round(median_ms, 3),
        "Throughput (images/sec)": round(1000 / median_ms, 2),
        "Run-to-run range (ms)": (
            f"{min(values):.3f}–{max(values):.3f}"
        )
    })

benchmark_results = pd.DataFrame(rows)
display(benchmark_results)

