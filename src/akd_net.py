class PlantSegmentationDataset(Dataset):
    def __init__(self, hf_dataset, split_name):
        self.samples = [
            i for i, row in enumerate(hf_dataset)
            if str(row["split"]).lower() == split_name.lower()
        ]
        self.hf_dataset = hf_dataset
        self.split_name = split_name

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, index):
        row = self.hf_dataset[self.samples[index]]

        image = row["image"].convert("RGB")
        mask = row["mask"].convert("L")

        image = image_transform(image)

        mask = mask.resize(
            (IMAGE_SIZE[0], IMAGE_SIZE[1]),
            resample=Image.Resampling.NEAREST
        )

        mask = np.array(mask, dtype=np.uint8)
        mask = (mask == 255).astype(np.int64)

        return image, torch.from_numpy(mask)

