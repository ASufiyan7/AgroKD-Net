STD  = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)

def get_logits(model, images):
    output = model(images)
    return output["out"] if isinstance(output, dict) else output

def show_predictions(num_images=5):
    teacher_eval.eval()
    baseline_eval.eval()
    kd_eval.eval()

    indices = np.linspace(
        0, len(test_data) - 1,
        min(num_images, len(test_data)),
        dtype=int
    )

    fig, axes = plt.subplots(
        len(indices), 5,
        figsize=(18, 4 * len(indices)),
        squeeze=False
    )

    titles = [
        "Original image",
        "Ground truth",
        "Teacher",
        "Baseline student",
        "KD student"
    ]

    for row, idx in enumerate(indices):
        image, mask = test_data[idx]

        # Add batch dimension and send image to device
        x = image.unsqueeze(0).to(DEVICE)

        with torch.no_grad():
            teacher_pred = get_logits(teacher_eval, x).argmax(1)[0]
            baseline_pred = get_logits(baseline_eval, x).argmax(1)[0]
            kd_pred = get_logits(kd_eval, x).argmax(1)[0]

        # Undo ImageNet normalization for display
        display_image = (
            image.cpu() * STD + MEAN
        ).clamp(0, 1).permute(1, 2, 0).numpy()

        ground_truth = mask.cpu().numpy()

        images_to_show = [
            display_image,
            ground_truth,
            teacher_pred.cpu().numpy(),
            baseline_pred.cpu().numpy(),
            kd_pred.cpu().numpy()
        ]

        for col, shown in enumerate(images_to_show):
            ax = axes[row, col]

            if col == 0:
                ax.imshow(shown)
            else:
                ax.imshow(shown, cmap="gray", vmin=0, vmax=1)

            ax.axis("off")

            if row == 0:
                ax.set_title(titles[col], fontsize=11)

    plt.tight_layout()
    plt.show()

show_predictions(num_images=5)

