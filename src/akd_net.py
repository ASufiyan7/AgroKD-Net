for epoch in range(1, EPOCHS_KD + 1):
    student_kd.train()
    running_loss = 0.0
    start_time = time.time()

    for images, masks in train_loader:
        images = images.to(DEVICE)
        masks = masks.to(DEVICE)

        optimizer_kd.zero_grad(set_to_none=True)

        # Ground-truth supervision
        student_logits = student_kd(images)
        loss_gt = ce_loss(student_logits, masks)

        # Teacher soft predictions
        with torch.no_grad():
            teacher_logits = teacher(images)["out"]

        # KL divergence between teacher and student distributions
        T = 4.0
        alpha = 0.5

        loss_gt = ce_loss(student_logits, masks)

        loss_distill = F.kl_div(
            F.log_softmax(student_logits / T, dim=1),
            F.softmax(teacher_logits / T, dim=1),
            reduction="batchmean"
        ) * (T ** 2) / (masks.shape[-2] * masks.shape[-1])

        loss = (1 - alpha) * loss_gt + alpha * loss_distill

        loss.backward()
        optimizer_kd.step()

        running_loss += loss.item()

